create table paciente (
    idpaciente            integer generated by default as identity primary key,
    codigo                varchar(20)  not null unique,
    ci                    varchar(20)  not null unique,        -- RF02: CI único
    nombres               varchar(100) not null,
    apellidos             varchar(100) not null,
    fechanacimiento       date not null check (fechanacimiento > date '1900-01-01'),
    sexo                  varchar(1) not null check (sexo in ('M', 'F', 'O')),
    telefono              varchar(30)  not null,
    email                 varchar(150),
    direccion             varchar(255),
    tiposangre            varchar(5) check (tiposangre in ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    aceptanotificaciones  boolean not null default true,
    estado                varchar(20) not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO')),
    idusuario             integer unique references usuario(idusuario)   -- cuenta del portal (opcional)
);
create index paciente_nombre_idx on paciente (lower(apellidos), lower(nombres));

create table contactoemergencia (
    idcontacto  integer generated by default as identity primary key,
    nombre      varchar(150) not null,
    parentesco  varchar(50)  not null,
    telefono    varchar(30)  not null,
    idpaciente  integer not null references paciente(idpaciente) on delete cascade
);
create index contactoemergencia_idpaciente_idx on contactoemergencia(idpaciente);

create table historiaclinica (
    idhistoria              integer generated by default as identity primary key,
    numero                  varchar(20) not null unique,
    antecedentespersonales  text,
    antecedentesfamiliares  text,
    alergias                text,
    enfermedadescronicas    text,
    medicacionhabitual      text,
    idpaciente              integer not null unique references paciente(idpaciente) on delete cascade
);

-- =====================================================================
-- P4 · Gestión de citas
-- =====================================================================
create table estadocita (
    codigo        varchar(20) primary key,
    nombre        varchar(50) not null,
    descripcion   varchar(255),
    ocupahorario  boolean not null default true
);

create sequence cita_codigo_seq;

create table cita (
    idcita             integer generated by default as identity primary key,
    codigo             varchar(30) not null unique
                       default 'CM-' || lpad(nextval('cita_codigo_seq')::text, 4, '0'),
    fecha              date not null,
    horainicio         time not null,
    horafin            time not null,
    modalidad          varchar(20) not null default 'PRESENCIAL' check (modalidad in ('PRESENCIAL', 'VIRTUAL')),
    motivo             varchar(255),
    fecharegistro      timestamptz not null default now(),
    idpaciente         integer not null references paciente(idpaciente),        -- RN03 / RN11
    idmedico           integer not null references medico(idmedico),            -- RN03 / RN11
    idespecialidad     integer not null references especialidad(idespecialidad),
    codigoestado       varchar(20) not null default 'PROGRAMADA' references estadocita(codigo),
    idusuarioregistro  integer references usuario(idusuario),
    constraint cita_rango_ck check (horafin > horainicio),
    -- RF07 / RN07: un médico no puede tener citas superpuestas (las canceladas no ocupan horario)
    constraint cita_sin_cruce_medico exclude using gist (
        idmedico with =, tsrange(fecha + horainicio, fecha + horafin) with &&
    ) where (codigoestado <> 'CANCELADA'),
    -- Un paciente tampoco puede estar en dos citas a la vez
    constraint cita_sin_cruce_paciente exclude using gist (
        idpaciente with =, tsrange(fecha + horainicio, fecha + horafin) with &&
    ) where (codigoestado <> 'CANCELADA')
);
create index cita_idpaciente_idx on cita(idpaciente);
create index cita_idmedico_fecha_idx on cita(idmedico, fecha);
create index cita_fecha_idx on cita(fecha);
create index cita_idespecialidad_idx on cita(idespecialidad);
create index cita_codigoestado_idx on cita(codigoestado);
create index cita_idusuarioregistro_idx on cita(idusuarioregistro);

create table historialcita (
    idhistorial    integer generated by default as identity primary key,
    accion         varchar(30) not null,
    fechaanterior  date,
    horaanterior   time,
    fechanueva     date,
    horanueva      time,
    motivo         varchar(255),
    fecha          timestamptz not null default now(),
    idcita         integer not null references cita(idcita) on delete cascade,
    codigoestado   varchar(20) not null references estadocita(codigo),
    idusuario      integer references usuario(idusuario)
);
create index historialcita_idcita_idx on historialcita(idcita);
create index historialcita_codigoestado_idx on historialcita(codigoestado);
create index historialcita_idusuario_idx on historialcita(idusuario);

-- =====================================================================
-- P5 · Atención médica
-- =====================================================================
create table consulta (
    idconsulta          integer generated by default as identity primary key,
    fechahora           timestamptz not null default now(),
    motivo              varchar(255),
    peso                numeric(5,2) check (peso between 0.5 and 400),
    talla               numeric(5,2) check (talla between 20 and 250),
    presionarterial     varchar(20),
    temperatura         numeric(4,1) check (temperatura between 30 and 45),
    frecuenciacardiaca  integer check (frecuenciacardiaca between 20 and 250),
    examenfisico        text,
    diagnostico         text not null,
    observaciones       text,
    idcita              integer not null unique references cita(idcita)
);

create table medicamento (
    idmedicamento  integer generated by default as identity primary key,
    nombre         varchar(150) not null,
    presentacion   varchar(100),
    estado         varchar(20) not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO'))
);

create table tratamiento (
    idtratamiento  integer generated by default as identity primary key,
    dosis          varchar(100) not null,
    frecuencia     varchar(100) not null,
    duracion       varchar(100) not null,
    indicaciones   text,
    idconsulta     integer not null references consulta(idconsulta) on delete cascade,
    idmedicamento  integer not null references medicamento(idmedicamento)
);
create index tratamiento_idconsulta_idx on tratamiento(idconsulta);
create index tratamiento_idmedicamento_idx on tratamiento(idmedicamento);

create table catalogoestudio (
    idcatalogo   integer generated by default as identity primary key,
    nombre       varchar(150) not null,
    categoria    varchar(100),
    descripcion  varchar(255),
    estado       varchar(20) not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO'))
);

create table estudio (
    idestudio         integer generated by default as identity primary key,
    indicaciones      text,
    estado            varchar(20) not null default 'SOLICITADO'
                      check (estado in ('SOLICITADO', 'EN_PROCESO', 'COMPLETADO', 'CANCELADO')),
    fechasolicitud    timestamptz not null default now(),
    fecharesultado    timestamptz,
    resultado         text,
    archivoresultado  varchar(500),
    idconsulta        integer not null references consulta(idconsulta) on delete cascade,
    idcatalogo        integer not null references catalogoestudio(idcatalogo)
);
create index estudio_idconsulta_idx on estudio(idconsulta);
create index estudio_idcatalogo_idx on estudio(idcatalogo);

create table notificacion (
    idnotificacion  integer generated by default as identity primary key,
    tipo            varchar(30) not null,
    canal           varchar(20) not null default 'APP' check (canal in ('APP', 'EMAIL', 'SMS', 'WHATSAPP')),
    mensaje         text not null,
    programadapara  timestamptz,
    enviadaen       timestamptz,
    leidaen         timestamptz,
    idcita          integer references cita(idcita) on delete cascade,
    idestudio       integer references estudio(idestudio) on delete cascade
);
create index notificacion_idcita_idx on notificacion(idcita);
create index notificacion_idestudio_idx on notificacion(idestudio);
