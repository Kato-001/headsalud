-- =====================================================================
-- NovaSol Salud · Sistema Web de Gestión de Citas Médicas
-- 01 · Esquema de la base de datos (PostgreSQL)
-- ---------------------------------------------------------------------
-- Todo vive en el esquema "clinica" (no expuesto por la API pública de Supabase).
-- Implementa el diagrama de clases (Docs/Diagrama de Clinica.svg) más
-- tres tablas de soporte: PERMISO y ROLPERMISO (permisos por rol) y
-- SESION (sesiones PHP persistentes, necesarias en Vercel).
-- =====================================================================

create schema if not exists clinica;
create schema if not exists extensions;   -- ya existe en Supabase; se crea en PostgreSQL local
set search_path = clinica, extensions, public;

create extension if not exists btree_gist with schema extensions;   -- restricciones EXCLUDE (citas sin cruces)

-- Normaliza un texto para comparar nombres: minúsculas, sin tildes y sin espacios repetidos
create or replace function normalizar(t text) returns text
language sql immutable parallel safe set search_path = '' as $$
    select translate(lower(regexp_replace(trim(t), '\s+', ' ', 'g')), 'áéíóúüñ', 'aeiouun')
$$;

-- =====================================================================
-- P1 · Seguridad y acceso
-- =====================================================================
create table rol (
    idrol        integer generated by default as identity primary key,
    nombre       varchar(50)  not null unique,
    descripcion  varchar(255)
);

create table permiso (
    idpermiso    integer generated by default as identity primary key,
    codigo       varchar(60)  not null unique,       -- ej. citas.gestionar
    nombre       varchar(120) not null,
    modulo       varchar(60)  not null
);

create table rolpermiso (
    idrol        integer not null references rol(idrol) on delete cascade,
    idpermiso    integer not null references permiso(idpermiso) on delete cascade,
    primary key (idrol, idpermiso)
);
create index rolpermiso_idpermiso_idx on rolpermiso(idpermiso);

create table usuario (
    idusuario     integer generated by default as identity primary key,
    nombre        varchar(150) not null,
    username      varchar(50)  not null,
    email         varchar(150) not null,
    password      varchar(255) not null,               -- hash de password_hash() (bcrypt)
    estado        varchar(20)  not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO')),
    ultimoacceso  timestamptz,
    idrol         integer not null references rol(idrol)
);
create unique index usuario_username_uk on usuario (lower(username));
create unique index usuario_email_uk on usuario (lower(email));
create index usuario_idrol_idx on usuario(idrol);

create table bitacora (
    idbitacora   integer generated by default as identity primary key,
    accion       varchar(50) not null,
    modulo       varchar(50) not null,
    tabla        varchar(50),
    idregistro   integer,
    descripcion  text,
    ip           varchar(64),
    fecha        timestamptz not null default now(),
    idusuario    integer references usuario(idusuario)
);
create index bitacora_idusuario_idx on bitacora(idusuario);
create index bitacora_fecha_idx on bitacora(fecha desc);

create table configuracion (
    clave        varchar(100) primary key,
    valor        varchar(255) not null,
    descripcion  varchar(255)
);

-- Códigos de verificación para recuperar la contraseña por correo
-- (el código se guarda con password_hash(), vence a los 15 minutos y admite 5 intentos)
create table recuperacion (
    idrecuperacion  integer generated by default as identity primary key,
    idusuario       integer not null references usuario(idusuario) on delete cascade,
    codigohash      varchar(255) not null,
    expira          timestamptz not null,
    intentos        integer not null default 0 check (intentos >= 0),
    usado           boolean not null default false,
    ip              varchar(64),
    creado          timestamptz not null default now()
);
create index recuperacion_idusuario_idx on recuperacion(idusuario, creado desc);

-- Sesiones PHP (session_set_save_handler): permiten que la sesión sobreviva entre
-- las distintas instancias serverless de Vercel
create table sesion (
    id           varchar(128) primary key,
    datos        text not null default '',
    actualizado  timestamptz not null default now()
);
create index sesion_actualizado_idx on sesion(actualizado);

-- =====================================================================
-- P2 · Gestión médica
-- =====================================================================
create table especialidad (
    idespecialidad  integer generated by default as identity primary key,
    nombre          varchar(100) not null,
    descripcion     varchar(255),
    estado          varchar(20) not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO'))
);
-- RF04: no se repiten nombres normalizados ("Pediatría" = "pediatria ")
create unique index especialidad_nombre_uk on especialidad (normalizar(nombre));

create table medico (
    idmedico             integer generated by default as identity primary key,
    codigo               varchar(20)  not null unique,
    registroprofesional  varchar(50)  not null unique,
    nombres              varchar(100) not null,
    apellidos            varchar(100) not null,
    telefono             varchar(30),
    email                varchar(150),
    estado               varchar(20) not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO')),
    idusuario            integer not null unique references usuario(idusuario)
);

create table medicoespecialidad (
    idmedico        integer not null references medico(idmedico) on delete cascade,
    idespecialidad  integer not null references especialidad(idespecialidad),
    primary key (idmedico, idespecialidad)
);
create index medicoespecialidad_idespecialidad_idx on medicoespecialidad(idespecialidad);

create table horario (
    idhorario   integer generated by default as identity primary key,
    diasemana   integer not null check (diasemana between 1 and 7),   -- 1 = lunes … 7 = domingo (ISO)
    horainicio  time not null,
    horafin     time not null,
    estado      varchar(20) not null default 'ACTIVO' check (estado in ('ACTIVO', 'INACTIVO')),
    idmedico    integer not null references medico(idmedico) on delete cascade,
    constraint horario_rango_ck check (horafin > horainicio),
    -- RF05: un médico no puede tener dos horarios activos que se crucen el mismo día
    constraint horario_sin_cruce exclude using gist (
        idmedico with =, diasemana with =,
        tsrange(date '2000-01-01' + horainicio, date '2000-01-01' + horafin) with &&
    ) where (estado = 'ACTIVO')
);
create index horario_idmedico_idx on horario(idmedico);

create table bloqueoagenda (
    idbloqueo   integer generated by default as identity primary key,
    fecha       date not null,
    horainicio  time,
    horafin     time,
    tipo        varchar(30) not null check (tipo in ('FERIADO', 'VACACION', 'PERMISO', 'OTRO')),
    motivo      varchar(255),
    idmedico    integer not null references medico(idmedico) on delete cascade,
    constraint bloqueo_rango_ck check ((horainicio is null and horafin is null)
        or (horainicio is not null and horafin is not null and horafin > horainicio))
);
create index bloqueoagenda_idmedico_fecha_idx on bloqueoagenda(idmedico, fecha);

